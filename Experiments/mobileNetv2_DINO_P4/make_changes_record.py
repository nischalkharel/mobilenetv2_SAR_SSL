"""Records how this folder differs from Experiments/mobileNetv2_DINO (A1), file by file.

Run from the repository root (after any edit in this folder):
    python Experiments/mobileNetv2_DINO_P4/make_changes_record.py

For every file of this folder it writes diffs/<file>.diff (unified diff against the A1 file of the same name;
empty for identical copies) and diffs/SUMMARY.md: status (identical / modified / new), SHA-256 of both files,
line counts and the size of the diff. CHANGES.md explains every modified hunk by hand; this script is the
mechanical check that nothing else changed. Exit code 1 if a file listed as identical in CHANGES.md differs.
"""
import difflib
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
A1 = HERE.parent / "mobileNetv2_DINO"
DIFFS = HERE / "diffs"
# Files that CHANGES.md promises are byte-for-byte copies of the A1 files.
IDENTICAL = ["dino.py", "data.py", "model.py", "engine.py", "utils.py",
             "reference/SOURCE.md", "reference/baseline_original", "reference/dino-main_original"]
SKIP_DIRS = {"outputs", "diffs", "__pycache__"}
# P4's own documents: A1 has files of the same name with unrelated content, so they are reported as new, not diffed.
OWN_DOCS = {"README.md", "CHANGES.md"}


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def files_of(folder: Path):
    for p in sorted(folder.rglob("*")):
        if p.is_file() and not any(part in SKIP_DIRS for part in p.relative_to(folder).parts):
            yield p.relative_to(folder).as_posix()


def main():
    DIFFS.mkdir(exist_ok=True)
    for old in DIFFS.glob("*.diff"):
        old.unlink()
    rows, failed = [], []
    for rel in files_of(HERE):
        here, there = HERE / rel, A1 / rel
        if rel.endswith((".pyc",)):
            continue
        if not there.exists() or rel in OWN_DOCS:
            rows.append((rel, "new", "-", sha(here)[:12], "-", len(here.read_text(encoding="utf-8", errors="replace").splitlines()), 0))
            continue
        a = there.read_text(encoding="utf-8", errors="replace").splitlines()
        b = here.read_text(encoding="utf-8", errors="replace").splitlines()
        diff = list(difflib.unified_diff(a, b, f"A1/{rel}", f"P4/{rel}", lineterm=""))
        status = "identical" if sha(here) == sha(there) else "modified"
        if status == "modified":
            (DIFFS / (rel.replace("/", "__") + ".diff")).write_text("\n".join(diff) + "\n", encoding="utf-8")
        rows.append((rel, status, sha(there)[:12], sha(here)[:12], len(a), len(b), sum(1 for l in diff if l[:1] in "+-" and not l.startswith(("+++", "---")))))
        promised = any(rel == i or rel.startswith(i + "/") for i in IDENTICAL)
        if promised and status != "identical":
            failed.append(rel)
    missing = [rel for rel in files_of(A1) if not (HERE / rel).exists() and not rel.startswith(("diffs/", "tools/"))
               and rel not in ("DINO_CHANGES.md", "README.md")]
    lines = ["# Files of Experiments/mobileNetv2_DINO_P4 versus Experiments/mobileNetv2_DINO (A1)", "",
             "Generated by make_changes_record.py. Status: identical = byte-for-byte copy of the A1 file; modified = copied",
             "and changed (the hunks are explained in CHANGES.md; the exact diff is in diffs/); new = no A1 counterpart.", "",
             "| File | Status | A1 sha256 | P4 sha256 | A1 lines | P4 lines | changed lines |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    lines += ["", f"A1 files not copied (not needed here): {', '.join(missing) if missing else 'none'}; A1's DINO_CHANGES.md,",
              "README.md, tools/ and diffs/ are A1's own records of its DINO extracts and stay there."]
    (DIFFS / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    if failed:
        print(f"\nERROR: promised identical but differs: {failed}")
        sys.exit(1)


if __name__ == "__main__":
    main()
